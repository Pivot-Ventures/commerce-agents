def weekly(daily: int) -> int:
    return daily * 6


def monthly(daily: int) -> int:
    return daily * 22


def item(
    *,
    product_id: str,
    title: str,
    brand: str,
    price: int,
    category: str,
    listing_type: str,
    location: str,
    short: str,
    long: str,
    image: str,
    source: str = "yard",
    source_url: str | None = None,
    price_source: str | None = None,
    machine_class: str,
    daily_rate: int | None = None,
    stock: int = 1,
    in_stock: bool | None = None,
    labels: list[str] | None = None,
    rating: float = 4.5,
    review_count: int = 20,
    specs: dict[str, str] | None = None,
    extras: dict[str, str] | None = None,
    unit: str | None = None,
    rate_unit: str | None = None,
    price_on_request: bool = False,
    yard: str | None = None,
    region: str = "Central",
) -> dict:
    available = in_stock if in_stock is not None else stock > 0
    attrs: dict[str, str] = {
        "listing_type": listing_type,
        "machine_class": machine_class,
        "location": location,
        "region": region,
        "stock": str(stock),
        "min_quantity": "1",
        "source": source,
        "published": "true",
        "yard": yard or f"EquipAccess {location}",
    }
    if daily_rate is not None:
        attrs["rate_type"] = "Daily"
        attrs["daily_rate"] = str(daily_rate)
        attrs["weekly_rate"] = str(weekly(daily_rate))
        attrs["monthly_rate"] = str(monthly(daily_rate))
    if source_url:
        attrs["source_url"] = source_url
    if price_source:
        attrs["price_source"] = price_source
    if unit:
        attrs["unit"] = unit
    if rate_unit:
        attrs["rate_unit"] = rate_unit
    if price_on_request:
        attrs["price_on_request"] = "true"
    if extras:
        attrs.update(extras)
    row: dict = {
        "currency": "UGX",
        "rating": rating,
        "review_count": review_count,
        "labels": labels
        if labels is not None
        else (["In stock"] if available else (["For sale"] if listing_type == "Sale" else [])),
        "in_stock": available,
        "product_id": product_id,
        "title": title,
        "brand": brand,
        "price": 0 if price_on_request else price,
        "category": category,
        "image_url": f"/products/{image}",
        "short_description": short,
        "long_description": long,
        "specs": specs or {},
        "review_highlights": [],
        "attributes": attrs,
    }
    return row


def hire(**kwargs) -> dict:
    daily = int(kwargs.pop("daily_rate"))
    kwargs.setdefault("price", daily)
    return item(listing_type="Rent", daily_rate=daily, **kwargs)


